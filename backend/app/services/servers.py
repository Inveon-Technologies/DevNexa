"""Remote servers: other machines DevNexa deploys apps to and manages over SSH.

A server is reached with an SSH key (generated by DevNexa, or pasted). Its key, known host key and a `Host
devnexa-server-<id>` block are written under `servers_dir`, and the backend's ~/.ssh/config includes them, so

* the Docker CLI drives the server's own Docker engine with `DOCKER_HOST=ssh://devnexa-server-<id>`: the Deploy
  Agent builds, runs, health-checks, monitors, backs up and rolls back apps there exactly as it does locally, and
* the dashboard can check the server (OS, Docker, CPU, memory, disk, containers), run a command on it, read and
  restart its containers, and install Docker on it.

The DevNexa host itself is the implicit local server (no row, `server_id` None). A deployment's server is kept in
its `options["server_id"]`, so redeploys, rollbacks, agent fixes and test URLs stay on the same machine.
"""

