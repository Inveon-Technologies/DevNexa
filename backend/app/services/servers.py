log = logging.getLogger("devnexa.servers")

NAME = re.compile(r"^[a-z0-9][a-z0-9-]{0,39}$")
HOST = re.compile(r"^[A-Za-z0-9.:_-]{1,255}$")
USER = re.compile(r"^[a-z_][a-z0-9_.-]{0,31}$", re.I)
CONTAINER = re.compile(r"^[A-Za-z0-9][A-Za-z0-9_.-]{0,127}$")
ACTIVE = ("queued", "cloning", "building", "starting", "running")

# Prints `key=value` facts, then one JSON line per container. Plain POSIX sh, nothing to install.
PROBE = r"""
echo "__devnexa__=1"
echo "os=$( (. /etc/os-release 2>/dev/null && echo "$PRETTY_NAME") || uname -s)"
echo "kernel=$(uname -r)"
echo "arch=$(uname -m)"
echo "hostname=$(hostname 2>/dev/null)"
echo "user=$(id -un)"
echo "cpus=$(nproc 2>/dev/null || getconf _NPROCESSORS_ONLN 2>/dev/null)"
echo "mem_total_mb=$(free -m 2>/dev/null | awk '/^Mem:/{print $2}')"
echo "mem_used_mb=$(free -m 2>/dev/null | awk '/^Mem:/{print $3}')"
echo "disk_total=$(df -h / 2>/dev/null | awk 'NR==2{print $2}')"
echo "disk_free=$(df -h / 2>/dev/null | awk 'NR==2{print $4}')"
echo "disk_used_pct=$(df / 2>/dev/null | awk 'NR==2{print $5}')"
echo "load=$(cut -d' ' -f1-3 /proc/loadavg 2>/dev/null)"
echo "uptime=$(uptime -p 2>/dev/null || uptime)"
echo "docker=$(docker version --format '{{.Server.Version}}' 2>/dev/null)"
echo "docker_error=$(docker version --format '{{.Server.Version}}' 2>&1 >/dev/null | tail -n1)"
echo "__containers__"
docker ps -a --format '{{json .}}' 2>/dev/null
"""

INSTALL_DOCKER = r"""
set -e
if [ "$(id -u)" = 0 ]; then S=""; else S="sudo -n"; fi
if command -v docker >/dev/null 2>&1; then echo "Docker is already installed: $(docker --version)"; else
  command -v curl >/dev/null 2>&1 || { $S apt-get update -y && $S apt-get install -y curl; }
  curl -fsSL https://get.docker.com -o /tmp/get-docker.sh
  $S sh /tmp/get-docker.sh
fi
$S systemctl enable --now docker 2>/dev/null || true
if [ "$(id -u)" != 0 ]; then $S usermod -aG docker "$(id -un)" && echo "Added $(id -un) to the docker group."; fi
docker version --format 'Docker {{.Server.Version}} is ready.' 2>/dev/null || $S docker version --format 'Docker {{.Server.Version}} is ready.'
"""


class ServerError(Exception):
    def __init__(self, message: str, status: int = 400):
        super().__init__(message)
        self.status = status


def now() -> datetime:
    return datetime.now(timezone.utc)


def _executor():
    from ..agents import deploy

    return deploy.executor


# -------------------------------------------------------------------- keys
def generate_keypair(comment: str = "devnexa") -> tuple[str, str]:
    """A new ed25519 key pair: (OpenSSH private key, `ssh-ed25519 AAAA... comment` public line)."""
    from cryptography.hazmat.primitives import serialization
    from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PrivateKey

    key = Ed25519PrivateKey.generate()
    private = key.private_bytes(serialization.Encoding.PEM, serialization.PrivateFormat.OpenSSH,
                                serialization.NoEncryption()).decode()
    public = key.public_key().public_bytes(serialization.Encoding.OpenSSH, serialization.PublicFormat.OpenSSH).decode()
    return private, f"{public} {comment}"


def parse_private_key(text: str, comment: str = "devnexa") -> tuple[str, str]:
    """Check a pasted private key and derive its public line. Passphrase-protected keys are refused, because
    deploys run unattended."""
    from cryptography.hazmat.primitives import serialization

    text = text.strip().replace("\r\n", "\n") + "\n"
    try:
        if "OPENSSH PRIVATE KEY" in text:
            key = serialization.load_ssh_private_key(text.encode(), password=None)
        else:
            key = serialization.load_pem_private_key(text.encode(), password=None)
    except TypeError as e:
        raise ServerError("That key has a passphrase. Paste a key without one, or let DevNexa generate a key.") from e
    except ValueError as e:
        raise ServerError("That does not look like an SSH private key (OpenSSH or PEM format).") from e
    public = key.public_key().public_bytes(serialization.Encoding.OpenSSH, serialization.PublicFormat.OpenSSH).decode()
    return text, f"{public} {comment}"


def authorize_command(server: Server) -> str:
    """The one-liner to run on the server so DevNexa's key may log in."""
    return ("mkdir -p ~/.ssh && chmod 700 ~/.ssh && echo " + shlex.quote(server.public_key.strip())
            + " >> ~/.ssh/authorized_keys && chmod 600 ~/.ssh/authorized_keys")


# --------------------------------------------------------- ssh plumbing
def alias(server_id: int) -> str:
    return f"devnexa-server-{server_id}"


def docker_host(server_id: int) -> str:
    return f"ssh://{alias(server_id)}"


def address(server: Server) -> str:
    return server.address or server.host


def _dir() -> Path:
    return Path(get_settings().servers_dir)


def ssh_config_path() -> Path:
    return _dir() / "ssh_config"


def materialize(server: Server) -> None:
    """Write this server's key, known host key and Host block (mode 600), and make sure the backend's own
    ~/.ssh/config includes them so `ssh` and the Docker CLI can reach it by alias."""
    base = _dir()
    d = base / str(server.id)
    d.mkdir(parents=True, exist_ok=True)
    os.chmod(base, 0o700)
    os.chmod(d, 0o700)
    key = d / "key"
    _write(key, server.private_key if server.private_key.endswith("\n") else server.private_key + "\n")
    kh = d / "known_hosts"
    if server.known_hosts and (not kh.exists() or not kh.read_text().strip()):
        _write(kh, server.known_hosts)
    elif not kh.exists():
        _write(kh, "")
    _write(d / "config", "\n".join([
        f"Host {alias(server.id)}",
        f"  HostName {server.host}",
        f"  Port {server.ssh_port}",
        f"  User {server.username}",
        f"  IdentityFile {key}",
        "  IdentitiesOnly yes",
        f"  UserKnownHostsFile {kh}",
        "  StrictHostKeyChecking accept-new",
        "  BatchMode yes",
        "  ConnectTimeout 10",
        "  ServerAliveInterval 15",
        "  ServerAliveCountMax 4",
        # One SSH connection is reused for the many short docker commands a deploy and the monitor run.
        "  ControlMaster auto",
        f"  ControlPath {base}/cm-%C",
        "  ControlPersist 120",
        "",
    ]))
    _write(ssh_config_path(), f"Include {base}/*/config\n")
    _include_in_user_config()


def _write(path: Path, text: str) -> None:
    if path.exists() and path.read_text() == text:
        return
    path.write_text(text)
    os.chmod(path, 0o600)


def _include_in_user_config() -> None:
    line = f"Include {ssh_config_path()}"
    cfg = Path(os.path.expanduser(get_settings().servers_ssh_config))
    try:
        cur = cfg.read_text() if cfg.exists() else ""
        if line in cur.splitlines():
            return
        cfg.parent.mkdir(parents=True, exist_ok=True)
        os.chmod(cfg.parent, 0o700)
        cfg.write_text(f"# Added by DevNexa: remote deploy servers\n{line}\n\n{cur}")  # before any Host block
        os.chmod(cfg, 0o600)
    except OSError as e:  # pragma: no cover - read-only home: plain `ssh -F` calls still work
        log.warning("could not update %s: %s", cfg, e)


def forget(server_id: int) -> None:
    import shutil

    shutil.rmtree(_dir() / str(server_id), ignore_errors=True)


def ssh(server: Server, command: str, timeout: float | None = None, on_line=None) -> tuple[int, str]:
    materialize(server)
    cmd = ["ssh", "-F", str(ssh_config_path()), alias(server.id), "--", command]
    try:
        return _executor().run(cmd, on_line, timeout=timeout or get_settings().servers_command_timeout)
    except FileNotFoundError:
        return 127, ("The ssh client is not installed in the DevNexa backend. Rebuild it: "
                     "docker compose up -d --build backend")


def _save_known_hosts(server: Server) -> None:
    kh = _dir() / str(server.id) / "known_hosts"
    if kh.exists() and kh.read_text().strip():
        server.known_hosts = kh.read_text()


# ---------------------------------------------------- which server a command targets
_target: ContextVar[dict | None] = ContextVar("devnexa_server_target", default=None)


def current() -> dict | None:
    """The server docker commands in this context run on (None: the DevNexa host)."""
    return _target.get()


def target_info(server: Server) -> dict:
    return {"id": server.id, "name": server.name, "docker_host": docker_host(server.id),
            "address": address(server), "port_base": server.port_base}


@contextmanager
def use(server_id: int | None):
    """Run the docker commands inside this block on `server_id` (None: locally)."""
    info = None
    if server_id:
        from ..db import session_scope

        with session_scope() as db:
            server = db.get(Server, int(server_id))
            if not server:
                raise ServerError(f"Server #{server_id} was removed from DevNexa.", 404)
            materialize(server)
            info = target_info(server)
    token = _target.set(info)
    try:
        yield info
    finally:
        _target.reset(token)


@contextmanager
def use_for(dep: AppDeployment | None):
    with use((dep.options or {}).get("server_id") if dep else None) as info:
        yield info


def server_of_app(db: Session, app: str) -> int | None:
    dep = db.scalars(select(AppDeployment).where(AppDeployment.app == app, AppDeployment.status == "running")
                     .order_by(AppDeployment.id.desc())).first() or \
        db.scalars(select(AppDeployment).where(AppDeployment.app == app).order_by(AppDeployment.id.desc())).first()
    return (dep.options or {}).get("server_id") if dep else None


@contextmanager
def use_app(app: str):
    from ..db import session_scope

    with session_scope() as db:
        sid = server_of_app(db, app)
    with use(sid) as info:
        yield info


def env_for(server_id: int | None) -> dict:
    """Environment for a docker subprocess started outside the executor (log streaming)."""
    if not server_id:
        return {}
    from ..db import session_scope

    with session_scope() as db:
        server = db.get(Server, int(server_id))
        if not server:
            return {}
        materialize(server)
    return {"DOCKER_HOST": docker_host(int(server_id))}


# ------------------------------------------------------------------ CRUD
def get(db: Session, server_id: int) -> Server:
    s = db.get(Server, server_id)
    if not s:
        raise ServerError("server not found", 404)
    return s


def list_all(db: Session) -> list[Server]:
    return list(db.scalars(select(Server).order_by(Server.id)))


def _validate(name: str, host: str, username: str, ssh_port: int, port_base: int, addr: str) -> None:
    if not NAME.match(name):
        raise ServerError("Name: lowercase letters, digits and dashes (up to 40).")
    if not HOST.match(host) or host.startswith("-"):
        raise ServerError("Host: an IP address or hostname.")
    if addr and (not HOST.match(addr) or addr.startswith("-")):
        raise ServerError("App address: an IP address or hostname.")
    if not USER.match(username):
        raise ServerError("SSH user: a Linux user name such as ubuntu or root.")
    if not 1 <= ssh_port <= 65535:
        raise ServerError("SSH port must be between 1 and 65535.")
    if not 1024 <= port_base <= 64000:
        raise ServerError("App port range must start between 1024 and 64000.")


def create(db: Session, name: str, host: str, username: str, ssh_port: int = 22, private_key: str | None = None,
           addr: str = "", port_base: int = 20000, actor: str = "operator") -> Server:
    name, host, addr = name.strip().lower(), host.strip(), (addr or "").strip()
    _validate(name, host, username, ssh_port, port_base, addr)
    if db.scalars(select(Server).where(Server.name == name)).first() or name == "local":
        raise ServerError(f"A server named {name} already exists.", 409)
    comment = f"devnexa-{name}"
    priv, pub = parse_private_key(private_key, comment) if private_key and private_key.strip() \
        else generate_keypair(comment)
    server = Server(name=name, host=host, ssh_port=ssh_port, username=username, private_key=priv, public_key=pub,
                    address=addr, port_base=port_base, created_by=actor)
    db.add(server)
    db.flush()
    audit(db, actor, "server.add", "server", server.id, f"Added server {name} ({username}@{host}:{ssh_port})")
    return server


def update(db: Session, server: Server, actor: str = "operator", **fields) -> Server:
    vals = {k: v for k, v in fields.items() if v is not None}
    if "private_key" in vals:
        key = vals.pop("private_key")
        if key.strip():
            server.private_key, server.public_key = parse_private_key(key, f"devnexa-{server.name}")
    if vals.pop("regenerate_key", False):
        server.private_key, server.public_key = generate_keypair(f"devnexa-{server.name}")
    if "address" in vals:
        vals["address"] = vals["address"].strip()
    merged = {"name": server.name, "host": server.host, "username": server.username, "ssh_port": server.ssh_port,
              "port_base": server.port_base, "address": server.address, **vals}
    _validate(merged["name"], merged["host"], merged["username"], merged["ssh_port"], merged["port_base"],
              merged["address"])
    if merged["host"] != server.host or merged["ssh_port"] != server.ssh_port:
        server.known_hosts = ""  # a different machine: trust its host key afresh
        forget(server.id)
    for k in ("host", "username", "ssh_port", "port_base", "address"):
        setattr(server, k, merged[k])
    server.status = "new"
    audit(db, actor, "server.update", "server", server.id, f"Updated server {server.name}")
    return server


def apps_on(db: Session, server_id: int) -> list[str]:
    deps = db.scalars(select(AppDeployment).where(AppDeployment.status.in_(ACTIVE)))
    return sorted({d.app for d in deps if (d.options or {}).get("server_id") == server_id})


def delete(db: Session, server: Server, actor: str = "operator") -> None:
    apps = apps_on(db, server.id)
    if apps:
        raise ServerError(f"Stop or move the apps on {server.name} first: {', '.join(apps)}.", 409)
    audit(db, actor, "server.remove", "server", server.id, f"Removed server {server.name}")
    forget(server.id)
    db.delete(server)


# ------------------------------------------------------------ inspection
def parse_probe(text: str) -> tuple[dict, list[dict]]:
    facts: dict = {}
    containers: list[dict] = []
    in_containers = False
    for line in text.splitlines():
        if line.strip() == "__containers__":
            in_containers = True
            continue
        if in_containers:
            try:
                c = json.loads(line)
            except ValueError:
                continue
            containers.append({"id": c.get("ID"), "name": c.get("Names"), "image": c.get("Image"),
                               "state": c.get("State"), "status": c.get("Status"), "ports": c.get("Ports"),
                               "devnexa": "devnexa.app=" in (c.get("Labels") or "")})
        elif "=" in line:
            k, v = line.split("=", 1)
            facts[k.strip()] = v.strip()
    facts.pop("__devnexa__", None)
    for k in ("cpus", "mem_total_mb", "mem_used_mb"):
        if facts.get(k, "").isdigit():
            facts[k] = int(facts[k])
    return facts, containers


def check(db: Session, server: Server) -> dict:
    """Log in, read the machine's facts and its containers, and record whether it can take deploys."""
    code, out = ssh(server, PROBE, timeout=40)
    _save_known_hosts(server)
    server.checked_at = now()
    if "__devnexa__=1" not in out:
        server.status, server.error = "offline", _ssh_error(out, code)
        return {"status": server.status, "error": server.error, "facts": server.facts or {}, "containers": []}
    facts, containers = parse_probe(out)
    docker_error = facts.pop("docker_error", "")
    facts["containers"] = len(containers)
    facts["containers_running"] = sum(1 for c in containers if c["state"] == "running")
    server.facts = facts
    if facts.get("docker"):
        server.status, server.error = "online", None
    else:
        server.status = "no_docker"
        server.error = ("Docker is not installed." if not docker_error or "not found" in docker_error
                        else f"Docker is installed but {server.username} cannot use it: {docker_error}")
    return {"status": server.status, "error": server.error, "facts": facts, "containers": containers}


def _ssh_error(out: str, code: int) -> str:
    text = out.strip().splitlines()
    last = text[-1] if text else f"ssh exited with code {code}"
    hints = {
        "Permission denied": "The server refused DevNexa's key. Run the authorize command on the server "
                             "(as this SSH user), then check again.",
        "Connection refused": "Nothing answers on the SSH port. Check the port and that sshd is running.",
        "timed out": "The server did not answer. Check the address and that the firewall (or cloud security "
                     "group) allows SSH from the DevNexa server.",
        "Could not resolve": "That hostname does not resolve.",
        "REMOTE HOST IDENTIFICATION HAS CHANGED": "The server's host key changed since DevNexa first connected. "
                                                  "If you rebuilt the machine, edit the server and save it again.",
        "No route to host": "No route to that address.",
    }
    for k, v in hints.items():
        if k.lower() in out.lower():
            return f"{v} ({last})"
    return last


def run_command(db: Session, server: Server, command: str, actor: str, timeout: int | None = None) -> dict:
    command = command.strip()
    if not command:
        raise ServerError("Type a command to run.")
    audit(db, actor, "server.exec", "server", server.id, f"{server.name}: {command[:300]}")
    db.flush()
    code, out = ssh(server, command, timeout=min(max(timeout or 0, 5), 600) if timeout else None)
    _save_known_hosts(server)
    return {"exit_code": code, "output": out[-60000:], "command": command}


def container_action(db: Session, server: Server, container: str, action: str, actor: str) -> dict:
    if not CONTAINER.match(container):
        raise ServerError("invalid container name")
    cmds = {"logs": f"docker logs --tail 300 --timestamps {container} 2>&1", "restart": f"docker restart {container}",
            "stop": f"docker stop {container}", "start": f"docker start {container}"}
    if action not in cmds:
        raise ServerError("unknown action", 404)
    if action != "logs":
        audit(db, actor, f"server.container.{action}", "server", server.id, f"{server.name}: {action} {container}")
    code, out = ssh(server, cmds[action])
    return {"exit_code": code, "output": out[-60000:]}


def install_docker(server_id: int, actor: str) -> None:
    """Background job: install Docker with get.docker.com (needs root or passwordless sudo), then re-check."""
    from ..db import session_scope

    lines: list[str] = []

    def on_line(ln: str):
        lines.append(ln)
        if len(lines) % 20 == 0:
            with session_scope() as db:
                s = db.get(Server, server_id)
                if s:
                    s.job = {**(s.job or {}), "output": "\n".join(lines[-400:])}

    with session_scope() as db:
        server = get(db, server_id)
        audit(db, actor, "server.install_docker", "server", server_id, f"Install Docker on {server.name}")
        server.job = {"kind": "install_docker", "status": "running", "started_at": now().isoformat(), "output": ""}
        db.flush()
        db.expunge(server)
    code, out = ssh(server, INSTALL_DOCKER, timeout=900, on_line=on_line)
    with session_scope() as db:
        server = get(db, server_id)
        hint = ("\nThe SSH user needs root or passwordless sudo to install Docker." if "sudo" in out and code else "")
        server.job = {"kind": "install_docker", "status": "succeeded" if code == 0 else "failed",
                      "finished_at": now().isoformat(), "output": out[-30000:] + hint}
        # A new docker group membership only applies to new SSH sessions: drop the shared connection.
        cm = list(_dir().glob("cm-*"))
        for p in cm:
            try:
                p.unlink()
            except OSError:
                pass
        check(db, server)


def to_dict(db: Session, server: Server) -> dict:
    return {"id": server.id, "name": server.name, "host": server.host, "ssh_port": server.ssh_port,
            "username": server.username, "address": address(server), "custom_address": bool(server.address),
            "port_base": server.port_base, "status": server.status, "error": server.error,
            "facts": server.facts or {}, "job": server.job, "public_key": server.public_key,
            "authorize_command": authorize_command(server), "host_key_trusted": bool(server.known_hosts),
            "apps": apps_on(db, server.id), "created_by": server.created_by,
            "created_at": server.created_at.isoformat() if server.created_at else None,
            "checked_at": server.checked_at.isoformat() if server.checked_at else None}
